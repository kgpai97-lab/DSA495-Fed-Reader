"""Load the "Trillion Dollar Words" labeled FOMC sentences and summarize them.

Downloads gtfintechlab/fomc_communication from Hugging Face (cached under
data/raw/), saves each split as CSV in data/raw/, and writes a summary of the
fields, label mapping, year range, class balance and split overlap to
results/dataset_summary.md.

Run from the repo root:
    python src/load_fomc_dataset.py
"""

import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "raw"
RESULTS_DIR = ROOT / "results"

# Keep the Hugging Face cache inside data/raw/ so nothing lands in git
os.environ.setdefault("HF_HOME", str(RAW_DIR / "hf_cache"))
os.environ.setdefault("HF_HUB_DISABLE_SYMLINKS_WARNING", "1")

import pandas as pd  # noqa: E402
from datasets import load_dataset  # noqa: E402

DATASET = "gtfintechlab/fomc_communication"

# From the dataset card ("Label Interpretation"); the label column is a plain int
LABEL_NAMES = {0: "dovish", 1: "hawkish", 2: "neutral"}


def load_splits():
    ds = load_dataset(DATASET)
    splits = {}
    for name, split in ds.items():
        df = split.to_pandas()
        df["label_name"] = df["label"].map(LABEL_NAMES)
        splits[name] = df
    return splits


def class_balance(df):
    counts = df["label_name"].value_counts().reindex(LABEL_NAMES.values(), fill_value=0)
    shares = (counts / len(df) * 100).round(1)
    return pd.DataFrame({"count": counts, "pct": shares})


def summarize(splits):
    lines = [f"# Dataset summary: `{DATASET}`", ""]
    lines.append("Generated by `src/load_fomc_dataset.py`.")
    lines.append("")

    first = next(iter(splits.values()))
    lines.append("## Fields")
    lines.append(", ".join(f"`{c}`" for c in first.columns if c != "label_name"))
    lines.append("")
    lines.append("## Label mapping (from the dataset card)")
    for k, v in LABEL_NAMES.items():
        lines.append(f"- {k} = {v}")
    lines.append("")

    lines.append("## Splits")
    lines.append("| split | rows | years | unique sentences |")
    lines.append("|---|---|---|---|")
    for name, df in splits.items():
        lines.append(
            f"| {name} | {len(df)} | {df['year'].min()} to {df['year'].max()} "
            f"| {df['sentence'].nunique()} |"
        )
    lines.append("")

    all_df = pd.concat(splits.values(), keys=splits.keys(), names=["split"]).reset_index(level=0).reset_index(drop=True)

    lines.append("## Class balance")
    for name, df in [*splits.items(), ("all", all_df)]:
        lines.append(f"**{name}**")
        lines.append("")
        lines.append(class_balance(df).to_markdown())
        lines.append("")

    lines.append("## Sentences per year (all splits)")
    by_year = pd.crosstab(all_df["year"], all_df["label_name"]).reindex(
        columns=LABEL_NAMES.values(), fill_value=0
    )
    by_year["total"] = by_year.sum(axis=1)
    lines.append(by_year.to_markdown())
    lines.append("")

    if {"train", "test"} <= splits.keys():
        train, test = splits["train"], splits["test"]
        overlap = set(train["sentence"]) & set(test["sentence"])
        shared_years = sorted(set(train["year"]) & set(test["year"]))
        lines.append("## Train/test split design")
        lines.append(f"- Exact duplicate sentences in both train and test: {len(overlap)}")
        lines.append(
            f"- Years present in both splits: {len(shared_years)} of "
            f"{all_df['year'].nunique()} (so the official split is not time-based)"
        )
        lines.append(
            "- No document type or meeting date field is provided, so meeting-grouped "
            "splits cannot be built from this dataset alone."
        )
        lines.append("")

    # Sanity check on `year`: a sentence should not cite a year well after its own
    cited = all_df["sentence"].str.findall(r"\b(?:19[89]\d|20[0-2]\d)\b")
    latest = cited.apply(lambda xs: max(map(int, xs)) if xs else 0)
    n_cite = int((latest > 0).sum())
    bad = all_df[latest > all_df["year"] + 1]
    lines.append("## Reliability of the `year` field")
    lines.append(
        f"- {n_cite} sentences cite a year in their text; {len(bad)} of them "
        f"({len(bad) / n_cite:.0%}) cite a year more than one year after their `year` value."
    )
    lines.append(
        "- This is a lower bound (mismatches in the other direction are not detectable "
        "this way), so `year` should not be trusted for time-based splits as is."
    )
    lines.append("")
    for _, row in bad.head(5).iterrows():
        lines.append(f"- (year={row['year']}) {row['sentence'][:200]}")
    lines.append("")

    lines.append("## Example sentences per label (train)")
    sample_from = splits.get("train", first)
    for label in LABEL_NAMES.values():
        lines.append(f"**{label}**")
        for _, row in sample_from[sample_from["label_name"] == label].head(3).iterrows():
            lines.append(f"- ({row['year']}) {row['sentence']}")
        lines.append("")

    return "\n".join(lines)


def main():
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    splits = load_splits()
    for name, df in splits.items():
        out = RAW_DIR / f"fomc_communication_{name}.csv"
        df.to_csv(out, index=False)
        print(f"saved {out.relative_to(ROOT)} ({len(df)} rows)")

    summary = summarize(splits)
    out = RESULTS_DIR / "dataset_summary.md"
    out.write_text(summary, encoding="utf-8")
    print(f"saved {out.relative_to(ROOT)}")
    print()
    print(summary)


if __name__ == "__main__":
    main()
