"""Build the evaluation splits for the labeled sentences.

Excluded before splitting:
  - 266 sentences found in several documents (n_candidate_docs > 1), whose document
    and date are ambiguous
  - speech header rows flagged by src/flag_sentences.py

Splits written to data/processed/splits.csv (one row per kept sentence, keyed by
`row_id`, the row position in labeled_sentences.csv):
  - fold_grouped: 5-fold, stratified by label, grouped by doc_id, so no document is
    in both train and test
  - time_split: "train" for year <= TIME_CUTOFF, "test" after; the headline
    look-ahead check
  - walk_fold: expanding-window folds; each fold tests on a 2-year block and
    trains on everything before it
  - official_split: the dataset's own train/test split, kept only as the leaky reference

Uses the recovered `year`/`date`, never the dataset's own `year` field.

Requires data/processed/labeled_sentences.csv and sentence_flags.csv. Run from the repo root:
    python src/prepare_splits.py
"""

from pathlib import Path

import pandas as pd
from sklearn.model_selection import StratifiedGroupKFold

ROOT = Path(__file__).resolve().parents[1]
PROCESSED_DIR = ROOT / "data" / "processed"
RESULTS_DIR = ROOT / "results"

SEED = 495
N_FOLDS = 5
TIME_CUTOFF = 2018
WALK_TEST_BLOCKS = [(2012, 2013), (2014, 2015), (2016, 2017), (2018, 2019), (2020, 2021), (2022, 2022)]


def load_kept():
    df = pd.read_csv(PROCESSED_DIR / "labeled_sentences.csv")
    df.index.name = "row_id"
    headers = set(pd.read_csv(PROCESSED_DIR / "sentence_flags.csv")["row_id"])
    ambiguous = df["n_candidate_docs"] > 1
    is_header = df.index.isin(headers)
    print(f"excluded {ambiguous.sum()} ambiguous and {is_header.sum()} header sentences")
    return df[~ambiguous & ~is_header].copy()


def add_grouped_folds(df):
    df["fold_grouped"] = -1
    cv = StratifiedGroupKFold(n_splits=N_FOLDS, shuffle=True, random_state=SEED)
    for fold, (_, test_idx) in enumerate(cv.split(df, df["label"], groups=df["doc_id"])):
        df.iloc[test_idx, df.columns.get_loc("fold_grouped")] = fold


def add_time_splits(df):
    df["time_split"] = (df["year"] <= TIME_CUTOFF).map({True: "train", False: "test"})
    df["walk_fold"] = -1  # -1: never a test sentence in a walk-forward fold
    for fold, (start, end) in enumerate(WALK_TEST_BLOCKS):
        df.loc[df["year"].between(start, end), "walk_fold"] = fold


def check(df):
    # No document or date leaks across any scheme
    for fold in range(N_FOLDS):
        test = df["fold_grouped"] == fold
        assert not set(df.loc[test, "doc_id"]) & set(df.loc[~test, "doc_id"]), fold
    assert df.loc[df["time_split"] == "train", "date"].max() < df.loc[df["time_split"] == "test", "date"].min()
    for fold, (start, _) in enumerate(WALK_TEST_BLOCKS):
        test = df[df["walk_fold"] == fold]
        assert df.loc[df["year"] < start, "date"].max() < test["date"].min()


def summarize(df):
    lines = ["# Evaluation splits", ""]
    lines.append(
        f"Generated by `src/prepare_splits.py` (seed {SEED}). {len(df)} sentences from "
        f"{df['doc_id'].nunique()} documents, after excluding the ambiguous multi-document "
        f"sentences and the speech header rows."
    )
    lines.append("")
    lines.append("## Grouped 5-fold (test sentences per fold, by label)")
    lines.append(pd.crosstab(df["fold_grouped"], df["label_name"], margins=True).to_markdown())
    lines.append("")
    lines.append("## Grouped 5-fold (test sentences per fold, by document type)")
    lines.append(pd.crosstab(df["fold_grouped"], df["doc_type"], margins=True).to_markdown())
    lines.append("")
    lines.append(f"## Time split (train: year <= {TIME_CUTOFF}), by document type")
    lines.append(pd.crosstab(df["time_split"], df["doc_type"], margins=True).to_markdown())
    lines.append("")
    lines.append("## Time split, by label")
    lines.append(pd.crosstab(df["time_split"], df["label_name"], margins=True).to_markdown())
    lines.append("")
    lines.append("## Walk-forward test blocks (sentences, by document type)")
    walk = df[df["walk_fold"] >= 0].assign(
        years=lambda x: x["walk_fold"].map(lambda i: "-".join(map(str, sorted(set(WALK_TEST_BLOCKS[i])))))
    )
    lines.append(pd.crosstab(walk["years"], walk["doc_type"], margins=True).to_markdown())
    lines.append("")
    return "\n".join(lines)


def main():
    df = load_kept()
    add_grouped_folds(df)
    add_time_splits(df)
    check(df)

    cols = ["sentence", "label", "label_name", "doc_id", "doc_type", "date", "year",
            "release_date", "match", "split", "fold_grouped", "time_split", "walk_fold"]
    out = PROCESSED_DIR / "splits.csv"
    df[cols].rename(columns={"split": "official_split"}).to_csv(out, encoding="utf-8")
    print(f"saved {out.relative_to(ROOT)} ({len(df)} rows)")

    summary = summarize(df)
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (RESULTS_DIR / "splits.md").write_text(summary, encoding="utf-8")
    print(summary)


if __name__ == "__main__":
    main()
